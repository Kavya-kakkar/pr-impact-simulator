"""Markdown dossier rendering and JSON export."""

from __future__ import annotations

from dataclasses import fields, is_dataclass
from enum import Enum
from pathlib import Path
from typing import Any

from ..model import Change, Classification, DocDrift, Dossier


def render_dossier(dossier: Dossier) -> str:
    risk = dossier.risk
    lines: list[str] = [
        f"# PR Impact Dossier - `{Path(dossier.repo).name}`",
        "",
        f"`{dossier.base_rev}` ({dossier.base_sha}) -> "
        f"`{dossier.head_rev}` ({dossier.head_sha})",
        "",
        f"**Verdict: {risk.band} - {risk.total}/100** - {_verdict_sentence(dossier)}",
        "",
        "## Risk breakdown",
        "",
        "| Factor | Raw value | Cap | Weight | Contribution | Note |",
        "| --- | ---: | ---: | ---: | ---: | --- |",
    ]
    for factor in risk.factors:
        lines.append(
            f"| {factor.name} | {factor.raw} | {factor.cap} | "
            f"{factor.weight:g} | {factor.contribution:g} | {factor.explanation} |"
        )
    lines.extend(["", f"`{risk.formula}`", ""])

    breaking = [c for c in dossier.changes if c.classification is Classification.BREAKING]
    review = [c for c in dossier.changes if c.classification is Classification.NEEDS_HUMAN]
    additive = [c for c in dossier.changes if c.classification is Classification.ADDITIVE]

    lines.extend(_change_section("Breaking changes", breaking))
    lines.extend(_change_section("Needs human review", review))
    lines.extend(_change_section("Additive changes", additive))
    lines.extend(_coverage_section(dossier))
    lines.extend(_doc_section(dossier.doc_drift))
    lines.extend(_skeleton_section(dossier))
    lines.extend(["## Rollback checklist", ""])
    lines.extend(f"{index}. {step}" for index, step in enumerate(dossier.rollback_steps, 1))
    lines.extend(["", "## Limitations", ""])
    if dossier.limitations:
        lines.extend(f"- {item}" for item in dossier.limitations)
    else:
        lines.append("- None recorded by the analyser.")
    lines.extend(
        [
            "",
            "## Evidence key",
            "",
            "Every claim above links to `path:line@revision`. Lines labelled `base` "
            "are read from the base revision, `head` from the head revision; diff "
            "pointers refer to the changed hunk.",
            "",
            "_Generated by PR Impact Simulator (deterministic mode). "
            "No claim is included without a file:line pointer._",
            "",
        ]
    )
    return "\n".join(lines)


def _verdict_sentence(dossier: Dossier) -> str:
    breaking = len(dossier.breaking_changes)
    broken = {
        (consumer.symbol, consumer.path)
        for change in dossier.breaking_changes
        for consumer in change.consumers
        if consumer.impact == "broken"
    }
    drift = len(dossier.doc_drift)
    uncovered = dossier.coverage.uncovered_added_lines
    parts = [
        f"{breaking} breaking change{'s' if breaking != 1 else ''}",
        f"{len(broken)} broken consumer{'s' if len(broken) != 1 else ''}",
        (
            f"{uncovered} uncovered new line{'s' if uncovered != 1 else ''}"
            if dossier.coverage.available
            else "coverage unavailable"
        ),
        f"{drift} documentation drift item{'s' if drift != 1 else ''}",
    ]
    return ", ".join(parts) + "."


def _change_section(title: str, changes: list[Change]) -> list[str]:
    if not changes:
        return [f"## {title}", "", "None detected.", ""]
    lines = [f"## {title}", ""]
    for index, change in enumerate(changes, 1):
        label = change.symbol.split("::", 1)[-1]
        lines.extend(
            [
                f"### {index}. `{label}` - {change.kind.value}",
                "",
                f"- Classification: **{change.classification.value}** "
                f"({change.confidence.value})",
            ]
        )
        if change.base_signature is not None:
            lines.append(f"- Before: `{change.base_signature.render(label)}`")
        if change.head_signature is not None:
            lines.append(f"- After: `{change.head_signature.render(label)}`")
        if change.route_before is not None:
            lines.append(f"- Route before: `{change.route_before.route_id}`")
        if change.route_after is not None:
            lines.append(f"- Route after: `{change.route_after.route_id}`")
        lines.append(f"- Summary: {change.summary}")
        if change.reasons:
            lines.append("- Reasons:")
            lines.extend(f"  - {reason}" for reason in change.reasons)
        if change.rationale:
            lines.append(f"- LLM note (non-evidentiary): {change.rationale}")
        lines.append("- Evidence:")
        lines.extend(f"  - `{item.loc()}` - {item.detail or item.kind}" for item in change.evidence)
        if change.consumers:
            lines.extend(
                [
                    "",
                    f"Consumers traced ({len(change.consumers)} call sites, "
                    f"{change.downstream_count} distinct functions):",
                    "",
                    "| Consumer | Call site | Depth | Impact | Detail |",
                    "| --- | --- | ---: | --- | --- |",
                ]
            )
            for consumer in change.consumers:
                lines.append(
                    f"| `{consumer.symbol}` | `{consumer.path}:{consumer.line}` "
                    f"@{consumer.revision} | {consumer.depth} | {consumer.impact} | "
                    f"{_escape(consumer.detail)} |"
                )
        lines.append("")
    return lines


def _coverage_section(dossier: Dossier) -> list[str]:
    coverage = dossier.coverage
    lines = ["## Test coverage", ""]
    lines.append(f"- Command: `{coverage.command or 'not run'}`")
    if coverage.head_percent is not None:
        base = f"{coverage.base_percent}%" if coverage.base_percent is not None else "unavailable"
        lines.append(f"- Total coverage: base {base} -> head {coverage.head_percent}%")
    lines.append(
        "- Test outcome: "
        + (
            "head green"
            if coverage.tests_passed
            else "head not green"
            if coverage.tests_passed is False
            else "unknown"
        )
    )
    if not coverage.available:
        lines.extend(["", "Coverage was **not available**; no uncovered-line count is claimed."])
    elif coverage.files:
        lines.extend(
            [
                "",
                "| File | Added lines | Covered | Uncovered | Uncovered line numbers |",
                "| --- | ---: | ---: | ---: | --- |",
            ]
        )
        for file in coverage.files:
            numbers = ", ".join(str(line) for line in file.uncovered_added) or "-"
            lines.append(
                f"| `{file.path}` | {len(file.added_lines)} | {file.covered_added} | "
                f"{len(file.uncovered_added)} | {numbers} |"
            )
    else:
        lines.append("")
        lines.append("No Python lines added by this PR required coverage.")
    lines.append("")
    return lines


def _doc_section(drifts: list[DocDrift]) -> list[str]:
    lines = ["## Documentation drift", ""]
    if not drifts:
        lines.extend(["None detected in checked markdown files.", ""])
        return lines
    for drift in drifts:
        lines.extend(
            [
                f"### `{drift.doc_path}:{drift.doc_line}` - {_escape(drift.snippet)}",
                "",
                f"- {drift.reason}",
                "- Evidence:",
                *(f"  - `{item.loc()}` - {item.detail or item.kind}" for item in drift.evidence),
                "",
            ]
        )
    return lines


def _skeleton_section(dossier: Dossier) -> list[str]:
    lines = ["## Generated test skeletons (incomplete)", ""]
    if not dossier.skeletons:
        lines.extend(
            ["No skeleton was generated: every changed public surface is executed "
             "by the existing suite, or coverage was unavailable.", ""]
        )
        return lines
    lines.append(
        "These files are committed under `.pr-impact/tests/` and skip themselves "
        "until a human fills in the TODOs."
    )
    lines.append("")
    for skeleton in dossier.skeletons:
        lines.append(f"- `{skeleton.path}` for `{skeleton.target_symbol}`")
    lines.append("")
    return lines


def dossier_to_dict(dossier: Dossier) -> dict[str, Any]:
    return _jsonable(dossier)


def _jsonable(value: Any) -> Any:
    if isinstance(value, Enum):
        return value.value
    if is_dataclass(value) and not isinstance(value, type):
        return {field.name: _jsonable(getattr(value, field.name)) for field in fields(value)}
    if isinstance(value, dict):
        return {str(key): _jsonable(item) for key, item in value.items()}
    if isinstance(value, (list, tuple, set)):
        return [_jsonable(item) for item in value]
    return value


def _escape(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")